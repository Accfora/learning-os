        "не имел законного права на ханский престол. Чтобы утвердить авторитет, ему требовалось силой принудить Русь к покорности. "
        "Однако Москва во главе с князем Дмитрием Ивановичем уже построила каменный Кремль, накопила силы и отказалась подчиняться."
