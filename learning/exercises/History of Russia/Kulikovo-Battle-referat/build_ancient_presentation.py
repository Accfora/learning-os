import os
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from pptx.enum.shapes import MSO_SHAPE
from PIL import Image

def build_presentation():
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank_layout = prs.slide_layouts[6]

    assets_dir = r"c:\Users\borod\OneDrive\Рабочий стол\МТУСИ\ОК&ВМ\learning-os-template\learning\exercises\History of Russia\Kulikovo-Battle-referat\assets"
    output_dir = r"c:\Users\borod\OneDrive\Рабочий стол\МТУСИ\ОК&ВМ\learning-os-template\learning\exercises\History of Russia\Kulikovo-Battle-referat"
    output_path = os.path.join(output_dir, "Куликовская_битва.pptx")

    # Древнерусская летописная палитра
    COLOR_PARCHMENT = RGBColor(246, 241, 233)     # Состаренный пергамент
    COLOR_PARCHMENT_CARD = RGBColor(255, 252, 247)# Карточка рукописи
    COLOR_CINNABAR = RGBColor(140, 38, 30)         # Русская киноварь (глубокий красный)
    COLOR_GOLD = RGBColor(184, 134, 11)           # Состаренное червонное золото
    COLOR_DARK_WOOD = RGBColor(58, 43, 37)        # Мореный дуб
    COLOR_INK = RGBColor(34, 30, 28)              # Чернила
    COLOR_MUTED = RGBColor(115, 102, 92)          # Пояснения

    def draw_manuscript_background(slide):
        bg = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, prs.slide_height)
        bg.fill.solid()
        bg.fill.fore_color.rgb = COLOR_PARCHMENT
        bg.line.fill.background()

        m1 = Inches(0.25)
        outer_frame = slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE, m1, m1, 
            prs.slide_width - m1 * 2, prs.slide_height - m1 * 2
        )
        outer_frame.fill.background()
        outer_frame.line.color.rgb = COLOR_GOLD
        outer_frame.line.width = Pt(1.5)

        m2 = Inches(0.35)
        inner_frame = slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE, m2, m2, 
            prs.slide_width - m2 * 2, prs.slide_height - m2 * 2
        )
        inner_frame.fill.background()
        inner_frame.line.color.rgb = COLOR_CINNABAR
        inner_frame.line.width = Pt(1.0)

    def add_slide_header(slide, title, category="ИСТОРИЯ РОССИИ • КУЛИКОВСКАЯ БИТВА 1380 ГОДА"):
        cat_box = slide.shapes.add_textbox(Inches(0.6), Inches(0.45), Inches(12.133), Inches(0.35))
        ctf = cat_box.text_frame
        ctf.word_wrap = True
        ctf.margin_left = ctf.margin_top = ctf.margin_right = ctf.margin_bottom = 0
        p_c = ctf.paragraphs[0]
        p_c.text = category.upper()
        p_c.font.size = Pt(10)
        p_c.font.bold = True
        p_c.font.color.rgb = COLOR_GOLD
        p_c.font.name = "Georgia"

        title_box = slide.shapes.add_textbox(Inches(0.6), Inches(0.75), Inches(12.133), Inches(0.65))
        ttf = title_box.text_frame
        ttf.word_wrap = True
        ttf.margin_left = ttf.margin_top = ttf.margin_right = ttf.margin_bottom = 0
        p_t = ttf.paragraphs[0]
        p_t.text = title
        p_t.font.size = Pt(21)
        p_t.font.bold = True
        p_t.font.color.rgb = COLOR_CINNABAR
        p_t.font.name = "Georgia"

        line = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.6), Inches(1.42), Inches(12.133), Inches(0.02))
        line.fill.solid()
        line.fill.fore_color.rgb = COLOR_GOLD
        line.line.fill.background()

    def add_image_with_caption(slide, filename, left, top, max_w, max_h, caption_text=""):
        img_full_path = os.path.join(assets_dir, filename)
        if not os.path.exists(img_full_path):
            print(f"Warning: image {filename} not found!")
            return None

        with Image.open(img_full_path) as im:
            iw, ih = im.size
        aspect = iw / ih

        avail_w = max_w
        avail_h = max_h - Inches(0.4) if caption_text else max_h
        
        target_w = avail_w
        target_h = target_w / aspect

        if target_h > avail_h:
            target_h = avail_h
            target_w = target_h * aspect

        img_left = left + (max_w - target_w) / 2
        img_top = top + (avail_h - target_h) / 2

        border_rect = slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE, img_left - Inches(0.04), img_top - Inches(0.04),
            target_w + Inches(0.08), target_h + Inches(0.08)
        )
        border_rect.fill.background()
        border_rect.line.color.rgb = COLOR_DARK_WOOD
        border_rect.line.width = Pt(1.5)

        pic = slide.shapes.add_picture(img_full_path, img_left, img_top, width=target_w, height=target_h)

        if caption_text:
            cap_box = slide.shapes.add_textbox(left, top + avail_h + Inches(0.05), max_w, Inches(0.35))
            ctf = cap_box.text_frame
            ctf.word_wrap = True
            ctf.margin_left = ctf.margin_top = ctf.margin_right = ctf.margin_bottom = 0
            p = ctf.paragraphs[0]
            p.alignment = PP_ALIGN.CENTER
            p.text = caption_text
            p.font.size = Pt(10)
            p.font.italic = True
            p.font.color.rgb = COLOR_MUTED
            p.font.name = "Georgia"

        return pic

