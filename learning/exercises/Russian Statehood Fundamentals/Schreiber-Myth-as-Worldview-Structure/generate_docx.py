# -*- coding: utf-8 -*-
import os
import docx
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_TAB_ALIGNMENT, WD_TAB_LEADER

def build_docx(output_path):
    doc = docx.Document()

    # Standard ГОСТ margins (A4: left 30mm, right 15mm, top 20mm, bottom 20mm)
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)
    section.left_margin = Cm(3.0)
    section.right_margin = Cm(1.5)

    style_normal = doc.styles['Normal']
    font = style_normal.font
    font.name = 'Times New Roman'
    font.size = Pt(14)
    font.color.rgb = RGBColor(0, 0, 0)

    def add_title_p(text, align=WD_ALIGN_PARAGRAPH.CENTER, bold=False, space_before=0, space_after=0, font_size=14):
        p = doc.add_paragraph()
        p.alignment = align
        p.paragraph_format.line_spacing = 1.15
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.first_line_indent = Cm(0)
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(font_size)
        run.bold = bold
        return p

    def add_h1(text, page_break_before=False):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(14)
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.keep_with_next = True
        if page_break_before:
            p.paragraph_format.page_break_before = True
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        run.bold = True
        return p

    def add_h2(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(10)
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        run.bold = True
        return p

    def add_p(text, bold_prefix=None, space_after=3):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.first_line_indent = Cm(1.25)
        if bold_prefix:
            r_b = p.add_run(bold_prefix)
            r_b.font.name = 'Times New Roman'
            r_b.font.size = Pt(14)
            r_b.bold = True
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        return p

    def add_bullet(bold_prefix, rest_text, space_after=2):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.first_line_indent = Cm(1.25)
        
        r_b = p.add_run('• ')
        r_b.font.name = 'Times New Roman'
        r_b.font.size = Pt(14)
        
        r_bold = p.add_run(bold_prefix)
        r_bold.font.name = 'Times New Roman'
        r_bold.font.size = Pt(14)
        r_bold.bold = True
        
        r_t = p.add_run(rest_text)
        r_t.font.name = 'Times New Roman'
        r_t.font.size = Pt(14)
        return p

    # ==================== СТР. 1: ТИТУЛЬНЫЙ ЛИСТ ====================
    add_title_p('МИНИСТЕРСТВО ЦИФРОВОГО РАЗВИТИЯ, СВЯЗИ И МАССОВЫХ КОММУНИКАЦИЙ РОССИЙСКОЙ ФЕДЕРАЦИИ', font_size=12, bold=True)
    add_title_p('Ордена Трудового Красного Знамени федеральное государственное бюджетное образовательное учреждение высшего образования', font_size=11)
    add_title_p('«МОСКОВСКИЙ ТЕХНИЧЕСКИЙ УНИВЕРСИТЕТ СВЯЗИ И ИНФОРМАТИКИ»', font_size=12, bold=True, space_after=10)
    add_title_p('Кафедра «Информационные технологии»', font_size=12, space_after=45)

    add_title_p('РЕФЕРАТ', font_size=18, bold=True, space_after=10)
    add_title_p('по дисциплине «Основы российской государственности»', font_size=14, space_after=14)
    add_title_p('на тему:\n«Миф как мировоззренческая структура\n(по концепции В. К. Шрейбера)»', font_size=16, bold=True, space_after=60)

    p_student = doc.add_paragraph()
    p_student.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p_student.paragraph_format.line_spacing = 1.2
    p_student.paragraph_format.space_after = Pt(70)
    p_student.paragraph_format.first_line_indent = Cm(0)
    r = p_student.add_run('Выполнил:\nстудент группы БВТ2602\nБородин Леонид Сергеевич\n\nПроверил:\nпреподаватель кафедры')
    r.font.name = 'Times New Roman'
    r.font.size = Pt(13)

    add_title_p('Москва, 2026', font_size=13)
    doc.add_page_break()

    # ==================== СТР. 2: ОГЛАВЛЕНИЕ С НАСТОЯЩИМИ ТАБУЛЯТОРАМИ ====================
    add_h1('ОГЛАВЛЕНИЕ')
    toc_items = [
        ('Введение', '3', False),
        ('1. Мировоззрение как схема принятия решений (В. К. Шрейбер)', '4', True),
        ('   1.1. Сущность мировоззрения и ситуация выбора', '4', False),
        ('   1.2. Триада мировоззренческих блоков', '5', False),
        ('2. Специфика мифологической картины мира', '6', True),
        ('   2.1. Объяснение через аналогию и антропоморфизм', '6', False),
        ('   2.2. Нерасчленённость знака и денотата (архаическая метафора)', '6', False),
        ('   2.3. Категория сакрального прецедента (in illo tempore)', '7', False),
        ('3. Обоснование ценностей и регуляция поведения в мифе', '7', True),
        ('   3.1. Нормативный статус мифа и детерминация выбора', '7', False),
        ('   3.2. Ритуал как практическое воплощение программ', '8', False),
        ('4. Проблема архаизации и ремифологизации в обществе', '8', True),
        ('   4.1. Дефицит рациональности и возвращение архаики', '8', False),
        ('   4.2. Политическая и медийная мифология XXI века', '9', False),
        ('Заключение', '9', False),
        ('Список использованных источников', '10', False)
    ]
    for item, pg, is_main in toc_items:
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.25
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.first_line_indent = Cm(0)
        # Настоящий табулятор Word с заполнителем точками на ширину 16.5 см
        p.paragraph_format.tab_stops.add_tab_stop(Cm(16.5), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
        
        r1 = p.add_run(item)
        r1.font.name = 'Times New Roman'
        r1.font.size = Pt(13)
        if is_main:
            r1.bold = True
            
        r2 = p.add_run(f'\t{pg}')
        r2.font.name = 'Times New Roman'
        r2.font.size = Pt(13)
        if is_main:
            r2.bold = True

    doc.add_page_break()

    # ==================== СТР. 3–4: ВВЕДЕНИЕ ====================
    add_h1('ВВЕДЕНИЕ')
    add_p('Казалось бы, XXI век — эпоха нейросетей, квантовых вычислений, генной инженерии и освоения дальнего космоса. Человечество окружило себя сложнейшими техническими системами и, по всем признакам Просвещения, должно мыслить предельно строго и рационально. Однако реальность демонстрирует поразительный парадокс: астрология, конспирология, теории заговора и слепая вера в медийные нарративы не просто сохраняются, но и стремительно процветают. В моменты кризисов и информационной перегрузки современный человек нередко действует не как хладнокровный логик, а как представитель архаического племени.')
    add_p('Именно этот парадокс определил исследовательский фокус российского философа Виктора Константиновича Шрейбера. Анализируя духовное состояние общества рубежа веков, он обратил внимание на то, что распад масштабных светских идеологий привел не к торжеству чистого разума, а к смысловому вакууму. Не имея монолитной объединяющей идеологии, но оставаясь вне строгой церковности, массовое сознание закономерно начало архаизироваться — восполнять дефицит ориентиров древними мифологическими структурами.')
    add_p('В программной научной работе «Миф как мировоззренческая структура» (2016) В. К. Шрейбер предложил принципиально новый методологический ракурс: отказаться от взгляда на миф как на наивную древнюю сказку и исследовать его через призму теории принятия решений. В его оптике мировоззрение — это практическая инструкция выбора, а миф — наиболее древняя и устойчивая архитектура принятия человеческих решений.')
    add_p(' необходимость концептуального осмысления структуры мифа как регулятора поведения в условиях современного дефицита рациональных ориентиров.', bold_prefix='Актуальность темы: ')
    add_p(' миф как историческая и актуальная форма общественного и индивидуального сознания.', bold_prefix='Объект исследования: ')
    add_p(' функционально-структурная организация мифологического мировоззрения в концепции В. К. Шрейбера.', bold_prefix='Предмет исследования: ')
    add_p(' осуществить комплексный теоретический анализ концепции мифа как мировоззренческой структуры В. К. Шрейбера и показать механизмы его влияния на поведение человека.', bold_prefix='Цель работы: ')
    add_p('Задачи исследования: 1) раскрыть основания понимания мировоззрения как схемы принятия решений; 2) проанализировать трёхкомпонентную модель мировоззрения; 3) исследовать специфику мифологической онтологии (аналогия, антропоморфизм, прецедент); 4) выявить механизм обоснования ценностей через ритуал; 5) оценить значение выводов Шрейбера для анализа современной ремифологизации.')

    doc.add_page_break()

    # ==================== СТР. 5: ГЛАВА 1 ====================
    add_h1('1. МИРОВОЗЗРЕНИЕ КАК СХЕМА ПРИНЯТИЯ РЕШЕНИЙ: МЕТОДОЛОГИЯ В. К. ШРЕЙБЕРА')
    add_h2('1.1. Сущность мировоззрения и структура ситуации выбора')
    add_p('В классических курсах мировоззрение нередко определяется пассивно и созерцательно — как совокупность взглядов человека на мир. В. К. Шрейбер аргументированно критикует такую трактовку за оторванность от практической жизни. Человек нуждается в мировоззрении не ради созерцания, а чтобы ежедневно делать выбор в условиях неопределённости, оценивать риски и выстраивать стратегии деятельности.')
    add_p('Опираясь на системный подход, В. К. Шрейбер постулирует: мировоззрение представляет собой практическую схему принятия решений. Всякая ситуация выбора объективно включает в себя три фундаментальных компонента:')
    add_bullet('1. Поле возможностей и условий: ', 'спектр объективных альтернатив поведения и внешних рамок их реализации в действительности.')
    add_bullet('2. Критерии предпочтения: ', 'шкала ценностей и приоритетов, на базе которой субъект отделяет «благое» от «пагубного», «должное» от «недопустимого».')
    add_bullet('3. Программа реализации: ', 'методы, алгоритмы и предписания, определяющие, как именно избранный путь осуществляется на практике.')
    add_p('Если у субъекта отсутствует хотя бы один из компонентов, выбор парализуется. Нельзя действовать без картины возможностей; нельзя выбрать без ценностных ориентиров; нельзя достичь результата без практического алгоритма. Предназначение мировоззрения — снабжать сознание ресурсами для преодоления неопределённости.')

