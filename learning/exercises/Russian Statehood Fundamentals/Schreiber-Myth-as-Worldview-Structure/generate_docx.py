    add_p('1. Картина мира (онтологический контур): моделирует реальность, задавая границы возможного и объясняя законы мироздания.')
    add_p('2. Блок ценностей (аксиологический контур): задаёт смысловые доминанты и служит фильтром селекции доступных альтернатив.')
    add_p('3. Блок программ поведения (праксиологический контур): переводит ценностные установки в систему норм, табу, ритуалов и сценариев деятельности.')
    add_p('В зависимости от наполнения этих блоков формируются исторические типы мировоззрения: мифологическое, религиозное, философское и научное.')

